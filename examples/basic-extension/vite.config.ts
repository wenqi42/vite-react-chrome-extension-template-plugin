import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";
import chromeExtension from "@vite-react-chrome-extension/plugin";

export default defineConfig({
  base: "./",
  build: {
    rollupOptions: {
      input: { background: "modules/background/background.ts" },
      output: {
        entryFileNames: chunk => chunk.name === "background"
          ? "background.js"
          : "assets/[name]-[hash].js",
        assetFileNames: asset => asset.name?.endsWith(".css")
          ? "assets/css/[name][extname]"
          : "assets/[name]-[hash][extname]",
      },
    },
  },
  plugins: [
    react(),
    chromeExtension({
      manifest: {
        name: "Basic Vite React Extension",
        description: "A smoke-test extension generated by the plugin.",
      },
      background: "background.js",
    }),
  ],
});
